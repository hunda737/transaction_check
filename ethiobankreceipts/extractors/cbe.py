"""CBE receipt extraction.

CBE retired the old ``apps.cbe.com.et:100`` PDF endpoint. Receipts are now served
as JSON: a share link ``https://mbreciept.cbe.com.et/<token>`` is only a viewer;
the data comes from a public API keyed by an opaque token minted by the CBE app.
The old FT-number + account scheme no longer produces a valid token.
"""
import os
import re
from urllib.parse import urlparse

from ethiobank_receipts.banks import resolve_url
from ethiobank_receipts.download import fetch_json
from ethiobank_receipts.errors import InvalidReference

# The CBE app identifies itself with these headers; the API rejects requests
# without them. They can be overridden if CBE rotates them.
CBE_APP_HEADERS = {
    "X-App-ID": os.environ.get(
        "ETHIOBANK_CBE_APP_ID", "d1292e42-7400-49de-a2d3-9731caa4c819"),
    "X-App-Version": os.environ.get(
        "ETHIOBANK_CBE_APP_VERSION", "0a01980b-9859-1369-8198-59f403820000"),
}

API_URL = "https://mb.cbe.com.et/api/v1/transactions/public/transaction-detail/{token}"


def _extract_token(ref_or_url: str) -> str:
    """Resolve a bare token or a full share URL down to the opaque token.

    ``resolve_url`` enforces the SSRF host check for full URLs and validates the
    token shape for bare references, so it runs first either way.
    """
    url = resolve_url("cbe", ref_or_url)
    token = urlparse(url).path.rsplit("/", 1)[-1]
    if not token:
        raise InvalidReference(f"Could not read a CBE token from {ref_or_url!r}")
    return token


def _money(value) -> str:
    """Strip a leading currency word and thousands separators: 'ETB 3.00' -> '3.00'."""
    if value is None:
        return None
    text = str(value).replace(",", "")
    match = re.search(r"-?\d+(?:\.\d+)?", text)
    return match.group(0) if match else None


def _first(value):
    """First element of a list-valued field, else the value itself."""
    if isinstance(value, list):
        return value[0] if value else None
    return value


def map_cbe_receipt(data: dict) -> dict:
    """Map a CBE transaction-detail JSON body onto the raw field names.

    Returns the same field names the previous PDF scraper produced, so
    ``schema.normalize("cbe", ...)`` maps it unchanged. Pure/offline.
    """
    return {
        "customer_name": data.get("debitAccountHolder"),
        "branch": None,
        "region_city": None,
        "payment_date": _first(data.get("dateTimes")),
        "reference_no": data.get("id"),
        "payer": data.get("debitAccountHolder"),
        "payer_account": data.get("debitAccountNo"),
        "receiver": data.get("creditAccountHolder"),
        "receiver_account": data.get("creditAccountNo"),
        "service": data.get("description") or _first(data.get("paymentDetails")),
        "transferred_amount": _money(data.get("amountCredited")),
        "commission": _money(data.get("serviceChargeValue")),
        "vat_on_commission": _money(data.get("vatValue")),
        "disaster_recovery": _money(data.get("drCharge")),
        "total_debited": _money(data.get("amountDebited")),
        "amount_in_words": None,
        "status": data.get("status"),
    }


def extract_cbe_receipt_info(ref_or_url: str) -> dict:
    """Fetch and map a CBE receipt from a share token or URL."""
    token = _extract_token(ref_or_url)
    data = fetch_json(API_URL.format(token=token), headers=CBE_APP_HEADERS)
    return map_cbe_receipt(data)


def extract_cbe_receipt_info_from_ft(ft_number: str, account_last8_or_full: str):
    """Retired: CBE no longer verifies by FT number + account.

    The current endpoint requires the opaque share token generated by the CBE
    app; it cannot be reconstructed from the FT number and account.
    """
    raise InvalidReference(
        "CBE no longer supports FT+account verification. Open the transaction in "
        "the CBE app, generate/share the receipt, and pass the share link "
        "(e.g. https://mbreciept.cbe.com.et/v2-...) or its token instead."
    )
